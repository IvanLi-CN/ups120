fn draw_char(fb: &mut FrameBuffer, x: u16, y: u16, ch: u8, color: Rgb565) -> u16 {
    if let Some(rows) = glyph(ch) {
        for (ry, row) in rows.iter().enumerate() {
            let mut mask = 1u8 << (GLYPH_W as u8 - 1);
            for rx in 0..GLYPH_W {
                if (row & mask) != 0 {
                    put_pixel_buffer(fb, x + rx, y + ry as u16, color);
                }
                mask >>= 1;
            }
        }
    } else {
        for rx in 0..GLYPH_W {
            put_pixel_buffer(fb, x + rx, y, color);
            put_pixel_buffer(fb, x + rx, y + GLYPH_H_U16 - 1, color);
        }
        for ry in 0..GLYPH_H {
            let ry = ry as u16;
            put_pixel_buffer(fb, x, y + ry, color);
            put_pixel_buffer(fb, x + GLYPH_W - 1, y + ry, color);
        }
    }
    CELL_W
}

fn draw_text(fb: &mut FrameBuffer, mut x: u16, y: u16, s: &str, color: Rgb565) -> u16 {
    for &b in s.as_bytes() {
        x += draw_char(fb, x, y, b.to_ascii_uppercase(), color);
    }
    x
}

fn draw_text_clipped(
    fb: &mut FrameBuffer,
    mut x: u16,
    y: u16,
    s: &str,
    color: Rgb565,
    max_width_px: u16,
) -> u16 {
    let start_x = x;
    for &b in s.as_bytes() {
        if x.saturating_sub(start_x) + CELL_W > max_width_px {
            break;
        }
        x += draw_char(fb, x, y, b.to_ascii_uppercase(), color);
    }
    x
}

fn text_width(s: &str) -> u16 {
    (s.as_bytes().len() as u16) * CELL_W
}

fn center_x(s: &str) -> u16 {
    let w = text_width(s);
    let cw = LOGICAL_WIDTH;
    let x = (cw.saturating_sub(w)) / 2;
    x.max(MARGIN_LR)
}

fn cell_to_x(cell: usize) -> u16 {
    MARGIN_LR + (cell as u16) * CELL_W
}

fn draw_value_right(
    fb: &mut FrameBuffer,
    col_start: usize,
    width_cells: usize,
    y: u16,
    text: &str,
    color: Rgb565,
) -> u16 {
    let text_cells = text.as_bytes().len();
    let start_cell = if text_cells >= width_cells {
        col_start
    } else {
        col_start + (width_cells - text_cells)
    };
    let x = cell_to_x(start_cell);
    draw_text(fb, x, y, text, color)
}

fn draw_celsius(fb: &mut FrameBuffer, x: u16, y: u16, color: Rgb565) -> u16 {
    let dot_x = x;
    let dot_y = if y > 0 { y - 1 } else { y };
    fill_rect_buffer(fb, dot_x, dot_y, dot_x + 1, dot_y + 1, color);
    draw_char(fb, x + 4, y, b'C', color)
}

// ---------------- Boot Screen -----------------
pub fn render_boot<SPI, CS, DC, DLY>(
    spi: &mut SPI,
    cs: &mut CS,
    dc: &mut DC,
    delay: &mut DLY,
) -> Result<(), SPI::Error>
where
    SPI: SpiBus<u8>,
    CS: OutputPin,
    DC: OutputPin,
    DLY: DelayNs,
{
    clear_framebuffer(BLACK);
    with_framebuffer(|fb| {
        let title = "UPS120";
        let y0 = MARGIN_TB;
        draw_text(fb, center_x(title), y0, title, WHITE);

        let subtitle = "SYSTEM BOOT";
        let y1 = y0 + LINE_H;
        draw_text(fb, center_x(subtitle), y1, subtitle, GRAY);

        let bar_w = LOGICAL_WIDTH - 2 * MARGIN_LR;
        let bar_h: u16 = 8;
        let bar_x = MARGIN_LR;
        let bar_y = LOGICAL_HEIGHT - MARGIN_TB - bar_h - LINE_H; // reserve 1 text line above

        let left = bar_x.saturating_sub(1);
        let right = (bar_x + bar_w).min(LOGICAL_WIDTH - 1);
        let top = bar_y.saturating_sub(1);
        let bottom = (bar_y + bar_h).min(LOGICAL_HEIGHT - 1);
        fill_rect_buffer(fb, left, top, right, top, GRAY);
        fill_rect_buffer(fb, left, bottom, right, bottom, GRAY);
        fill_rect_buffer(fb, left, top, left, bottom, GRAY);
        fill_rect_buffer(fb, right, top, right, bottom, GRAY);
    });
    flush_framebuffer(spi, cs, dc)?;

    let bar_w = LOGICAL_WIDTH - 2 * MARGIN_LR;
    let bar_h: u16 = 8;
    let bar_x = MARGIN_LR;
    let bar_y = LOGICAL_HEIGHT - MARGIN_TB - bar_h - LINE_H;

    for pct in (0..=100).step_by(5) {
        let fill = (u32::from(bar_w) * pct as u32 / 100) as u16;
        with_framebuffer(|fb| {
            fill_rect_buffer(
                fb,
                bar_x,
                bar_y,
                bar_x + bar_w - 1,
                bar_y + bar_h - 1,
                BLACK,
            );
            if fill > 0 {
                fill_rect_buffer(fb, bar_x, bar_y, bar_x + fill - 1, bar_y + bar_h - 1, GREEN);
            }

            let mut buf = heapless::String::<32>::new();
            let _ = write!(&mut buf, "INIT {}%", pct);
            fill_rect_buffer(
                fb,
                MARGIN_LR,
                bar_y - LINE_H,
                LOGICAL_WIDTH - MARGIN_LR - 1,
                bar_y - 1,
                BLACK,
            );
            draw_text(fb, center_x(&buf), bar_y - LINE_H, &buf, WHITE);
        });
        flush_framebuffer(spi, cs, dc)?;
        delay.delay_ms(40);
    }

    delay.delay_ms(400);
    Ok(())
}

