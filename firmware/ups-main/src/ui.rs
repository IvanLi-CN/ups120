fn fmt_voltage(mv: u32, buf: &mut heapless::String<16>) {
    buf.clear();
    let clamped = mv.min(99_990);
    let v_tenths = (clamped + 50) / 100; // 0.1V units
    let whole = v_tenths / 10;
    if whole >= 100 {
        let _ = buf.push_str(">99V");
        return;
    }
    let frac = v_tenths % 10;
    if whole >= 10 {
        let _ = write!(buf, "{:02}.{}V", whole, frac);
    } else {
        let hundredths = ((clamped + 5) / 10) % 10;
        let _ = write!(buf, "{}.{}{}V", whole, frac, hundredths);
    }
}

fn fmt_current(ma: u32, buf: &mut heapless::String<16>) {
    buf.clear();
    let clamped = ma.min(99_900);
    if clamped >= 10_000 {
        let amps = (clamped + 500) / 1000;
        if amps >= 100 {
            let _ = buf.push_str(">99A");
        } else {
            let _ = write!(buf, "{:>3}A", amps);
        }
    } else {
        let a_tenths = (clamped + 50) / 100;
        let whole = a_tenths / 10;
        let frac = a_tenths % 10;
        let _ = write!(buf, "{}.{}A", whole, frac);
    }
}

fn fmt_power(mw: u32, buf: &mut heapless::String<16>) {
    buf.clear();
    let w = (mw + 500) / 1000;
    if w > 999 {
        let _ = buf.push_str("999W");
    } else {
        let _ = write!(buf, "{:>3}W", w);
    }
}

fn fmt_soc<const N: usize>(pct: u8, buf: &mut heapless::String<N>) {
    buf.clear();
    let capped = pct.min(100);
    let _ = write!(buf, "{:>3}%", capped);
}

#[derive(Clone, Copy)]
pub enum SocDisplay {
    Percent,
    Voltage,
}

fn build_soc_text_and_color(
    soc: u8,
    vbat_mv: Option<u32>,
    which: SocDisplay,
) -> (heapless::String<16>, Rgb565) {
    let mut s: heapless::String<16> = heapless::String::new();
    match which {
        SocDisplay::Percent => {
            fmt_soc(soc, &mut s);
            let color = if soc <= 15 {
                RED
            } else if soc <= 30 {
                YELLOW
            } else {
                WHITE
            };
            (s, color)
        }
        SocDisplay::Voltage => {
            if let Some(mv) = vbat_mv {
                fmt_voltage(mv, &mut s);
                (s, ORANGE)
            } else {
                let _ = s.push_str(PLACEHOLDER);
                (s, GRAY)
            }
        }
    }
}

fn fmt_temp_digits(c: i16, buf: &mut heapless::String<8>) {
    buf.clear();
    let capped = c.clamp(-99, 199);
    let _ = write!(buf, "{}", capped);
}

fn fmt_fan(pct: u8, buf: &mut heapless::String<8>) {
    buf.clear();
    let capped = pct.min(100);
    let _ = write!(buf, "{:>3}%", capped);
}

fn fmt_uptime(secs: u32, buf: &mut heapless::String<16>) {
    buf.clear();
    const THRESHOLD: u32 = 72 * 3600;
    if secs < THRESHOLD {
        let h = secs / 3600;
        let m = (secs % 3600) / 60;
        let s = secs % 60;
        let _ = write!(buf, "{:02}:{:02}:{:02}", h, m, s);
    } else {
        let d = secs / 86400;
        let h = (secs % 86400) / 3600;
        let m = (secs % 3600) / 60;
        let _ = write!(buf, "{:02}D{:02}:{:02}", d, h, m);
    }
}

fn mode_text_and_color(mode: Mode) -> (&'static str, Rgb565) {
    match mode {
        Mode::Standby => ("MODE: STANDBY", GRAY),
        Mode::Charge => ("MODE: CHARGE", CYAN),
        Mode::Discharge => ("MODE: DISCHARGE", WHITE),
    }
}

fn batt_mode_short_text(mode: Mode) -> &'static str {
    match mode {
        Mode::Standby => "IDLE",
        Mode::Charge => "CHG",
        Mode::Discharge => "DSG",
    }
}

fn draw_batt_cell_entry(
    fb: &mut FrameBuffer,
    y: u16,
    col_start: usize,
    cell_index: u8,
    value_mv: Option<u16>,
    balancing_index: Option<u8>,
    blink_on: bool,
) {
    let mut label_buf: heapless::String<4> = heapless::String::new();
    let _ = write!(&mut label_buf, "{}:", cell_index);
    let x_label = cell_to_x(col_start);
    let _ = draw_text(fb, x_label, y, &label_buf, CYAN);

    let mut value_buf: heapless::String<8> = heapless::String::new();
    // 始终显示电压数值；仅通过颜色变化来表现“闪烁”。
    let present = if let Some(mv) = value_mv {
        let _ = write!(&mut value_buf, "{}", mv);
        true
    } else {
        let _ = value_buf.push_str(PLACEHOLDER);
        false
    };

    let is_balanced = balancing_index == Some(cell_index);
    let color = if !present {
        GRAY
    } else if is_balanced {
        // 被均衡的电芯：在两种颜色之间切换，实现“闪烁”效果。
        if blink_on {
            YELLOW
        } else {
            ORANGE
        }
    } else {
        ORANGE
    };

    let x_val = cell_to_x(col_start + 2);
    let _ = draw_text(fb, x_val, y, &value_buf, color);
}

fn draw_soc(fb: &mut FrameBuffer, y: u16, soc: u8) {
    let mut s: heapless::String<8> = heapless::String::new();
    fmt_soc(soc, &mut s);
    let color = if soc <= 15 {
        RED
    } else if soc <= 30 {
        YELLOW
    } else {
        WHITE
    };
    let x = LOGICAL_WIDTH - MARGIN_LR - text_width(&s);
    let _ = draw_text(fb, x, y, &s, color);
}

fn draw_trio_line(fb: &mut FrameBuffer, y: u16, head: &str, v: &str, a: &str, w: &str) {
    let _ = draw_text(fb, cell_to_x(COL_LABEL), y, head, CYAN);
    let volt_color = if v == PLACEHOLDER { GRAY } else { ORANGE };
    let curr_color = if a == PLACEHOLDER { GRAY } else { RED };
    let power_color = if w == PLACEHOLDER { GRAY } else { GREEN };
    let _ = draw_value_right(fb, COL_VOLT, VOLT_WIDTH_CELLS, y, v, volt_color);
    let _ = draw_value_right(fb, COL_CURR, CURRENT_WIDTH_CELLS, y, a, curr_color);
    let _ = draw_value_right(fb, COL_POWER, POWER_WIDTH_CELLS, y, w, power_color);
}

fn draw_aux_line(
    fb: &mut FrameBuffer,
    y: u16,
    slot: TempSlot,
    bat_c: Option<i16>,
    charger_c: Option<i16>,
    ups_c: Option<i16>,
    fan: u8,
) {
    let (label, temp) = match slot {
        TempSlot::Battery => ("BAT", bat_c),
        TempSlot::Charger => ("CHG", charger_c),
        TempSlot::Ups => ("UPS", ups_c),
    };

    let temp_label_x = cell_to_x(COL_LABEL);
    let _ = draw_text(fb, temp_label_x, y, label, CYAN);

    let mut temp_digits: heapless::String<8> = heapless::String::new();
    let color = if let Some(value) = temp {
        fmt_temp_digits(value, &mut temp_digits);
        WHITE
    } else {
        let _ = temp_digits.push_str(PLACEHOLDER);
        GRAY
    };
    let total_cells = temp_digits.as_bytes().len() + 1; // digits + 'C'
    let start_cell = if total_cells >= TEMP_VALUE_CELLS {
        AUX_TEMP_VALUE_COL
    } else {
        AUX_TEMP_VALUE_COL + (TEMP_VALUE_CELLS - total_cells)
    };
    let digits_x = cell_to_x(start_cell);
    let x_after_digits = draw_text(fb, digits_x, y, &temp_digits, color);
    let _ = draw_celsius(fb, x_after_digits, y, color);

    let _ = draw_text(fb, cell_to_x(AUX_FAN_LABEL_COL), y, "FAN", CYAN);
    let mut fan_buf: heapless::String<8> = heapless::String::new();
    fmt_fan(fan, &mut fan_buf);
    let _ = draw_value_right(fb, AUX_FAN_VALUE_COL, FAN_VALUE_CELLS, y, &fan_buf, WHITE);
}

pub fn render_dashboard_once<SPI, CS, DC>(
    spi: &mut SPI,
    cs: &mut CS,
    dc: &mut DC,
    model: &DashboardData,
) -> Result<(), SPI::Error>
where
    SPI: SpiBus<u8>,
    CS: OutputPin,
    DC: OutputPin,
{
    clear_framebuffer(BLACK);
    with_framebuffer(|fb| {
        let mut vs: heapless::String<16> = heapless::String::new();
        let mut as_: heapless::String<16> = heapless::String::new();
        let mut ws: heapless::String<16> = heapless::String::new();

        let y0 = MARGIN_TB;
        // Compose top-right battery area (percent or voltage)
        let (soc_text, soc_color) =
            build_soc_text_and_color(model.soc_pct, model.vbat_mv, model.soc_display);
        let soc_w = text_width(&soc_text);
        let soc_x = LOGICAL_WIDTH - MARGIN_LR - soc_w;
        let _ = draw_text(fb, soc_x, y0, &soc_text, soc_color);

        // Draw mode left, clipped to avoid overlap with right area
        let (mode_text, mode_color) = mode_text_and_color(model.mode);
        let max_mode_width = soc_x.saturating_sub(MARGIN_LR);
        let _ = draw_text_clipped(fb, MARGIN_LR, y0, mode_text, mode_color, max_mode_width);

        fmt_voltage(model.in_v_mv, &mut vs);
        fmt_current(model.in_a_ma, &mut as_);
        fmt_power(model.in_w_mw, &mut ws);
        let y1 = MARGIN_TB + LINE_H;
        draw_trio_line(fb, y1, "IN", &vs, &as_, &ws);

        let y2 = MARGIN_TB + 2 * LINE_H;
        match model.mode {
            Mode::Charge => {
                ws.clear();
                fmt_power(model.chg_w_mw, &mut ws);
                draw_trio_line(fb, y2, "CHG", PLACEHOLDER, PLACEHOLDER, &ws);
            }
            Mode::Standby => {
                let mut uptime: heapless::String<16> = heapless::String::new();
                fmt_uptime(model.uptime_secs, &mut uptime);
                draw_trio_line(fb, y2, "RUN ", &uptime, PLACEHOLDER, PLACEHOLDER);
            }
            Mode::Discharge => {
                vs.clear();
                as_.clear();
                ws.clear();
                fmt_voltage(model.out_v_mv, &mut vs);
                fmt_current(model.out_a_ma, &mut as_);
                fmt_power(model.out_w_mw, &mut ws);
                draw_trio_line(fb, y2, "OUT", &vs, &as_, &ws);
            }
        }

        let y3 = MARGIN_TB + 3 * LINE_H;
        draw_aux_line(
            fb,
            y3,
            model.temp_slot,
            model.bat_temp_c,
            model.charger_temp_c,
            model.ups_temp_c,
            model.fan_pct,
        );
    });
    flush_framebuffer(spi, cs, dc)
}

/// Render the battery detail page:
/// - Line1: `BAT <CHG|DSG|IDLE> <VV.VV>V <II.I>A`
/// - Line2: cells 1–3 as `<n>:<mV>`
/// - Line3: cells 4–5 plus optional `BAL<n>`
/// - Line4: `TEMP--°C--°C--°C--°C` with optional real values.
pub fn render_batt_detail_once<SPI, CS, DC>(
    spi: &mut SPI,
    cs: &mut CS,
    dc: &mut DC,
    model: &BattDetailData,
) -> Result<(), SPI::Error>
where
    SPI: SpiBus<u8>,
    CS: OutputPin,
    DC: OutputPin,
{
    clear_framebuffer(BLACK);
    with_framebuffer(|fb| {
        let y0 = MARGIN_TB;
        let y1 = MARGIN_TB + LINE_H;
        let y2 = MARGIN_TB + 2 * LINE_H;
        let y3 = MARGIN_TB + 3 * LINE_H;

        // ---- Line 1: BAT status + pack voltage/current ----
        let mut vbuf: heapless::String<16> = heapless::String::new();
        let mut ibuf: heapless::String<16> = heapless::String::new();

        let mut x = MARGIN_LR;
        x = draw_text(fb, x, y0, "BAT", CYAN);

        let status = batt_mode_short_text(model.mode);
        x = draw_text(fb, x + CELL_W, y0, status, CYAN);

        // Pack voltage
        vbuf.clear();
        let v_color = if let Some(mv) = model.pack_v_mv {
            fmt_voltage(mv, &mut vbuf);
            ORANGE
        } else {
            let _ = vbuf.push_str(PLACEHOLDER);
            GRAY
        };
        x = draw_text(fb, x + CELL_W, y0, &vbuf, v_color);

        // Pack current magnitude
        ibuf.clear();
        let i_color = if let Some(ma) = model.pack_i_ma {
            fmt_current(ma, &mut ibuf);
            RED
        } else {
            let _ = ibuf.push_str(PLACEHOLDER);
            GRAY
        };
        let _ = draw_text(fb, x + CELL_W, y0, &ibuf, i_color);

        // ---- Lines 2–3: per-cell voltages + balancing indicator ----
        // Place three entries per row at columns 0, 6, 12.
        let cols = [0usize, 6, 12];

        // Cells 1–3 on line 2
        for (slot, cell_index) in (1u8..=3).enumerate() {
            let idx = cell_index - 1;
            draw_batt_cell_entry(
                fb,
                y1,
                cols[slot],
                cell_index,
                model.cells_mv[idx as usize],
                model.balancing_index,
                model.blink_on,
            );
        }

        // Cells 4–5 on line 3
        for (slot, cell_index) in (4u8..=5).enumerate() {
            let idx = cell_index - 1;
            draw_batt_cell_entry(
                fb,
                y2,
                cols[slot],
                cell_index,
                model.cells_mv[idx as usize],
                model.balancing_index,
                model.blink_on,
            );
        }

        // Optional BAL<n> tag on the right of line 3.
        if let Some(idx) = model.balancing_index {
            let mut bal_buf: heapless::String<8> = heapless::String::new();
            let _ = write!(&mut bal_buf, "BAL{}", idx);
            // BAL 标签保持恒亮，不随 blink_on 变化，避免干扰电芯电压闪烁的视觉效果。
            let bal_color = YELLOW;
            let x_bal = cell_to_x(cols[2]);
            let _ = draw_text(fb, x_bal, y2, &bal_buf, bal_color);
        }

        // ---- Line 4: temperatures ----
        let mut temp_buf: heapless::String<8> = heapless::String::new();
        let label_x = cell_to_x(COL_LABEL);
        let _ = draw_text(fb, label_x, y3, "TEMP", CYAN);

        for (slot_idx, temp) in model.temps_c.iter().enumerate() {
            // Layout: `TEMP` (4 cells) + 1-cell gap, then 4 cells per temp slot.
            let start_cell = TEMP_LABEL_CELLS + 1 + slot_idx * TEMP_VALUE_CELLS;
            let x_digits = cell_to_x(start_cell);

            temp_buf.clear();
            let (digits_color, c_opt) = if let Some(v) = temp {
                fmt_temp_digits(*v, &mut temp_buf);
                (WHITE, Some(*v))
            } else {
                let _ = temp_buf.push_str(PLACEHOLDER);
                (GRAY, None)
            };
            let x_after_digits = draw_text(fb, x_digits, y3, &temp_buf, digits_color);
            let color = if c_opt.is_some() { digits_color } else { GRAY };
            let _ = draw_celsius(fb, x_after_digits, y3, color);
        }
    });
    flush_framebuffer(spi, cs, dc)
}
